import * as fs from "node:fs/promises";
import * as path from "node:path";
import type { OnModuleDestroy, OnModuleInit } from "@nestjs/common";
import { Injectable } from "@nestjs/common";
import Handlebars from "handlebars";
import puppeteer, { type Browser } from "puppeteer";

@Injectable()
export class ProfitReportPdfService implements OnModuleInit, OnModuleDestroy {
  private browser: Browser | null = null;
  private template: Handlebars.TemplateDelegate | null = null;

  async onModuleInit() {
    try {
      this.browser = await puppeteer.launch({ args: ["--no-sandbox", "--disable-setuid-sandbox"] });
    } catch {
      // Chromium not installed locally (e.g. dev without Docker) — render() will throw with clear message.
      this.browser = null;
    }
    Handlebars.registerHelper("cents", (v: number) =>
      new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" }).format(v / 100),
    );
    Handlebars.registerHelper("pct", (v: number) => `${v.toFixed(1)}%`);
    Handlebars.registerHelper("date", (d: string) =>
      new Date(d).toLocaleDateString("en-US", { year: "numeric", month: "short", day: "numeric" }),
    );
    // Resolve template relative to compiled dist or src
    const candidates = [
      path.join(__dirname, "templates/profit-report.hbs"),
      path.join(__dirname, "..", "pdf/templates/profit-report.hbs"),
      path.join(
        process.cwd(),
        "apps/server/src/modules/profit-report/pdf/templates/profit-report.hbs",
      ),
    ];
    for (const p of candidates) {
      try {
        const raw = await fs.readFile(p, "utf-8");
        this.template = Handlebars.compile(raw);
        break;
      } catch {
        // try next candidate
      }
    }
  }

  async onModuleDestroy() {
    await this.browser?.close();
  }

  async render(data: ProfitReportPdfData): Promise<Buffer> {
    if (!this.browser || !this.template)
      throw new Error(
        "ProfitReportPdfService not initialized — Chromium missing or template not found",
      );
    const html = this.template(data);
    const page = await this.browser.newPage();
    try {
      await page.setContent(html, { waitUntil: "networkidle0" as unknown as "load" });
      const pdf = await page.pdf({
        format: "A4",
        printBackground: true,
        margin: { top: "18mm", bottom: "18mm", left: "14mm", right: "14mm" },
        displayHeaderFooter: true,
        footerTemplate: `
          <div style="width:100%;font-size:8px;color:#999;padding:0 14mm;display:flex;justify-content:space-between;">
            <span>Generated by TAPT</span>
            <span>Page <span class="pageNumber"></span> of <span class="totalPages"></span></span>
          </div>`,
        headerTemplate: "<div></div>",
      });
      return Buffer.from(pdf);
    } finally {
      await page.close();
    }
  }
}

export interface ProfitReportPdfData {
  shop: { name: string; logoDataUri: string | null; phone: string; address: unknown };
  periodStart: string;
  periodEnd: string;
  generatedAt: string;
  generatedByName: string;
  reportId: string;
  revenue: { label: string; amountCents: number }[];
  expenses: { label: string; amountCents: number }[];
  totalRevenue: number;
  totalExpense: number;
  grossProfit: number;
  netProfit: number;
  profitMargin: number;
}
